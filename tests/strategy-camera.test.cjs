'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const base=path.join(__dirname,'../nbu-campus-3d');
const source=fs.readFileSync(path.join(base,'strategy-camera.js'),'utf8');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const sandbox={window:{}};
vm.runInNewContext(source,sandbox);
const camera=sandbox.window.CampusStrategyCamera;
const world={minX:-700,maxX:700,minZ:-650,maxZ:500};
test('iPhone portrait full-map button fits all original campus terrain',()=>{
 const viewport={w:390,h:844},result=camera.fit(world,viewport.w,viewport.h,60,75);
 const tangent=Math.tan(Math.PI/6);
 const visibleWidth=2*result.height*tangent*viewport.w/viewport.h;
 const visibleDepth=2*result.height*tangent;
 assert.ok(result.height>1700,'must zoom out well beyond the old 975 unit camera limit');
 assert.ok(result.height<8000,'fit height must be within the expanded camera far clip');
 assert.ok(visibleWidth>world.maxX-world.minX+140,'full horizontal world should fit');
 assert.ok(visibleDepth>world.maxZ-world.minZ+140,'full vertical world should fit');
 assert.equal(result.x,0);assert.equal(result.z,-75);
});
test('landscape fit is consistent and zoom can continue further out',()=>{
 const view=camera.fit(world,844,390,60,75);
 assert.ok(view.height>500&&view.height<camera.MAX_HEIGHT);
 assert.equal(camera.zoom(500,3),1500);
 assert.equal(camera.zoom(camera.MAX_HEIGHT,50),camera.MAX_HEIGHT);
 assert.equal(camera.zoom(camera.MIN_HEIGHT,.001),camera.MIN_HEIGHT);
});
test('finger drag pans in four directions with correct world-coordinate sign',()=>{
 const center={x:0,z:0},height=500,screen=800;
 const right=camera.pan(center,100,0,height,screen,60,false,world);
 const left=camera.pan(center,-100,0,height,screen,60,false,world);
 const down=camera.pan(center,0,100,height,screen,60,false,world);
 const up=camera.pan(center,0,-100,height,screen,60,false,world);
 assert.ok(right.x<0);assert.ok(left.x>0);assert.ok(down.z<0);assert.ok(up.z>0);
 assert.deepEqual(JSON.parse(JSON.stringify(center)),{x:0,z:0},'pan must not mutate original center');
 const limit=camera.pan({x:699,z:499},-100000,-100000,height,screen,60,false,world);
 assert.equal(limit.x,700);assert.equal(limit.z,500);
});
test('two-finger pinch tracks distance and center for combined pan and zoom',()=>{
 const a=camera.gestureMidpoint([{x:120,y:210},{x:220,y:210}]);
 const b=camera.gestureMidpoint([{x:110,y:240},{x:250,y:240}]);
 assert.equal(a.x,170);assert.equal(a.y,210);assert.equal(a.gap,100);
 assert.equal(b.x,180);assert.equal(b.y,240);assert.equal(b.gap,140);
 assert.ok(camera.zoom(500,a.gap/b.gap)<500,'moving fingers apart zooms inward');
});
test('in-game strategy uses the accessible map and can erase original roads and buildings',()=>{
 assert.match(html,/strategy-camera\.js\?v=/);
 assert.match(html,/id="fitStrategy"/);
 assert.match(html,/id="fitBuildWorld"/);
 assert.match(html,/id="eraseStrategy"/);
 assert.match(html,/id="selectStrategy"/);
 assert.match(html,/body\.strategyEditing:not\(\.cleanUi\) #strategyBar\{\s*display:flex!important/);
 assert.match(html,/document\.body\.classList\.toggle\("strategyEditing",buildMode\)/);
 assert.match(html,/strategyPan=true;strategyHeight=450/);
 assert.match(html,/function fitStrategyView\(\)/);
 assert.match(html,/strategyCamera\.fit\(WORLD/);
 assert.match(html,/strategyPanPixels\(dx,dy\)/);
 assert.match(html,/strategyZoomRatio\(pinchDistance\/gap\)/);
 assert.match(html,/strategyCamera\?\.gestureMidpoint/);
 assert.match(html,/const cam=new THREE\.PerspectiveCamera\(60,1,\.5,8000\)/);
 assert.match(html,/S\.fog\.far=buildMode\?Math\.max\(1350,strategyHeight\*5\):620/);
 assert.match(html,/function plannerDelete\(sel\)/);
 assert.match(html,/deletedFixedRoads\.add\(r\.id\)/);
 assert.match(html,/removedCampusBuildings\.add\(b\.n\)/);
 assert.match(html,/built\.splice\(sel\.index,1\)/);
 assert.match(html,/recordPlannerHistory\(\)/);
 assert.match(html,/storeBuild\(\);refreshPlannerEditor\(\)/);
});
